async function upsertCollection(collectionName, docs) {
  let batch = writeBatch(db);
  let operationCount = 0;

  for (const item of docs) {
    batch.set(doc(db, collectionName, item.id), item, { merge: true });
    operationCount += 1;

    if (operationCount === 400) {
      await batch.commit();
      batch = writeBatch(db);
      operationCount = 0;
    }
  }

  if (operationCount > 0) {
    await batch.commit();
  }
}

